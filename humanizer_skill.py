def strip_ai_punctuation_and_artifacts(text: str) -> str:
    """
    فیلتر نهایی ضد هوش مصنوعی منطبق با چک‌لیست `telegram-human-reply`:
    1. حذف کامل ویرگول، نقطه، دونقطه، علامت تعجب، علامت سوال، خط تیره و گیومه (با حفظ فرمت طبیعی)
    2. تبدیل ایمن نیم‌فاصله‌های کتابی به تایپ موبایلی طبیعی بدون خراب کردن کلمات مختوم به «ه»
    3. حذف بولت‌پوینت و شماره‌گذاری اول خطوط (فارسی و انگلیسی)
    4. حفظ فاصله یک خط خالی بین پاراگراف‌ها برای خوانایی در تلگرام
    """
    if not text:
        return ""

    cleaned = text.strip()

    # حذف پیشوندهای احتمالی که مدل ممکن است اضافه کند (فقط زمانی که بعدش دونقطه یا خط تیره آمده باشد)
    cleaned = re.sub(
        r"^(پاسخ|جواب|متن پیام|پیام تلگرام|خروجی)\s*[:：\-]+\s*",
        "",
        cleaned,
        flags=re.IGNORECASE,
    )

    # حذف بولت‌پوینت و شماره‌گذاری اول خط (شامل اعداد فارسی و انگلیسی)
    cleaned = re.sub(r"(?m)^\s*[\-\*•▪▫]+\s+", "", cleaned)
    cleaned = re.sub(r"(?m)^\s*[0-9۰-۹]+[\.\)\-]\s+", "", cleaned)

    # تبدیل الگوهای رایج نیم‌فاصله کتابی به تایپ موبایلی طبیعی
    # ۱. چسباندن «می» و «نمی» به فعل (می‌خوابی -> میخوابی، نمی‌خواهد -> نمیخواد)
    cleaned = re.sub(r"(^|[\s\u200c])(ن?می)\u200c+", r"\1\2", cleaned)

    # ۲. تبدیل «‌ها» در کلمات محاوره‌ای یا تبدیل نیم‌فاصله قبل از «ها» به فاصله معمولی
    cleaned = cleaned.replace("پارت‌ها", "پارتا").replace("پارت ها", "پارتا")
    cleaned = cleaned.replace("برنامه‌ات", "برنامت").replace("برنامه‌ام", "برنامم").replace("برنامه‌اش", "برنامش")
    cleaned = cleaned.replace("عقب‌افتادگی", "عقب افتادگی")
    cleaned = re.sub(r"\u200c+ها\b", " ها", cleaned)

    # ۳. مدیریت ایمن ضمایر ملکی/فعلی بعد از حروف:
    # اگر کلمه به «ه» ختم شود (مثل خسته‌ام، حوصله‌ات، جلسه‌اش)، نیم‌فاصله به فاصله تبدیل شود نه چسبیده (جلوگیری از خستهام/حوصلهات)
    cleaned = re.sub(r"ه\u200c+(ای|ام|ات|اش|ایم|اید|اند)(?=$|\s|[،.,؛:!؟?])", r"ه \1", cleaned)
    # در سایر حروف، نیم‌فاصله حذف یا به فاصله طبیعی تبدیل شود
    cleaned = re.sub(r"\u200c+(ای|ام|ات|اش|ایم|اید|اند)(?=$|\s|[،.,؛:!؟?])", r"\1", cleaned)
    cleaned = cleaned.replace("\u200c", " ")

    # تبدیل ساعت‌ها یا اعداد ممیزی به فرم گفتاری/فاصله‌دار ایمن قبل از حذف علائم
    cleaned = re.sub(r"([0-9۰-۹]+)[:٫.]([0-9۰-۹]+)", r"\1 و \2", cleaned)

    # حذف کامل تمام علائم نگارشی طبق قانون 2 اسکیل telegram-human-reply
    punctuation_to_remove = [
        ".", "،", ",", ";", "؛", ":", "!", "؟", "?",
        "«", "»", "\"", "'", "“", "”", "—", "–", "-",
        "(", ")", "[", "]", "{", "}", "…", "*", "_", "`", "~"
    ]
    for p in punctuation_to_remove:
        cleaned = cleaned.replace(p, " ")

    # نرمال‌سازی پاراگراف‌ها (حفظ یک خط خالی بین پاراگراف‌ها و حذف فاصله‌های اضافه داخل هر خط)
    raw_paragraphs = re.split(r"\n\s*\n", cleaned)
    clean_paragraphs = []
    for para in raw_paragraphs:
        lines = []
        for line in para.splitlines():
            line_clean = re.sub(r"[ \t]+", " ", line).strip()
            if line_clean:
                lines.append(line_clean)
        if lines:
            clean_paragraphs.append("\n".join(lines))

    return "\n\n".join(clean_paragraphs)
