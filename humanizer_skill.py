# ==================== الگوهای ازپیش‌کامپایل‌شده (Pre-Compiled Regexes & Translation Table) ====================
_RE_PREFIX = re.compile(
    r"^(?:پاسخ|جواب|متن پیام|پیام تلگرام|خروجی|متن انسانی\s*شده|نسخه بازنویسی\s*شده|حتما|بله حتما)\s*[:：\-!،.]*\s*",
    flags=re.IGNORECASE,
)
_RE_AI_INTRO_LINE = re.compile(
    r"^(?:حتما|بله حتما|البته|در ادامه|متن شما با لحن|نسخه بازنویسی)[^\n]*[:：]\s*\n+",
    flags=re.IGNORECASE,
)
_RE_AI_OUTRO_LINE = re.compile(
    r"\n+(?:امیدوارم این|اگر نیاز به تغییر|هر سوالی داشتی|موفق و پیروز باشی|با آرزوی موفقیت)[^\n]*$",
    flags=re.IGNORECASE,
)
_RE_BULLETS = re.compile(r"(?m)^\s*[\-\*•▪▫◦‣⁃]+\s+")
_RE_NUM_LIST = re.compile(r"(?m)^\s*[0-9۰-۹]+[\.\)\-\:]\s+")
_RE_MI_PREFIX = re.compile(r"(^|[\s\u200c])(ن?می)\u200c+")
_RE_HA_SUFFIX = re.compile(r"\u200c+ها\b")
_RE_TAR_SUFFIX = re.compile(r"\u200c+(تر|ترین)\b")
_RE_HEH_PRONOUN = re.compile(r"ه\u200c+(ای|ام|ات|اش|ایم|اید|اند)(?=$|\s|[،.,؛:!؟?])")
_RE_OTHER_PRONOUN = re.compile(r"\u200c+(ای|ام|ات|اش|ایم|اید|اند)(?=$|\s|[،.,؛:!؟?])")
_RE_TIME_OR_DEC = re.compile(r"([0-9۰-۹]+)[:٫.]([0-9۰-۹]+)")
_RE_ELI_BETWEEN_NUMS = re.compile(r"([0-9۰-۹]+)\s+الی\s+([0-9۰-۹]+)")
_RE_PARAGRAPH_SPLIT = re.compile(r"\n\s*\n")
_RE_SPACES = re.compile(r"[ \t]+")

