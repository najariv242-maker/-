# جدول ترجمه کاراکتری در سطح C برای جایگزینی فوق‌سریع علائم نگارشی و نیم‌فاصله در یک پاس
_PUNCTUATION_CHARS = ".,،;؛:!؟?«»\"'“”—–-()[]{}…*_`~\u200c"
_PUNCT_TRANSLATION_TABLE = str.maketrans({ch: " " for ch in _PUNCTUATION_CHARS})


def strip_ai_punctuation_and_artifacts(text: str) -> str:
    """
    فیلتر فوق‌سریع ضد هوش مصنوعی منطبق با چک‌لیست سخت‌گیرانه `telegram-human-reply`
    با استفاده از Regexهای پیش‌کامپایل‌شده و جدول ترجمه کاراکتری C-level
    """
    if not text:
        return ""

    cleaned = text.strip()
    cleaned = _RE_AI_INTRO_LINE.sub("", cleaned).strip()
    cleaned = _RE_AI_OUTRO_LINE.sub("", cleaned).strip()
    cleaned = _RE_PREFIX.sub("", cleaned)
    cleaned = _RE_BULLETS.sub("", cleaned)
    cleaned = _RE_NUM_LIST.sub("", cleaned)

    # ۱. ابتدا جایگزینی کلمات رسمی و کتابی قبل و بعد از حذف نیم‌فاصله
    for old_w, new_w in _FORMAL_REPLACEMENTS:
        if old_w in cleaned:
            cleaned = cleaned.replace(old_w, new_w)

    cleaned = _RE_MI_PREFIX.sub(r"\1\2", cleaned)
    for old_w, new_w in _FORMAL_REPLACEMENTS:
        if old_w in cleaned:
            cleaned = cleaned.replace(old_w, new_w)

    cleaned = _RE_HA_SUFFIX.sub(" ها", cleaned)
    cleaned = _RE_TAR_SUFFIX.sub(r"\1", cleaned)
    cleaned = _RE_HEH_PRONOUN.sub(r"ه \1", cleaned)
    cleaned = _RE_OTHER_PRONOUN.sub(r"\1", cleaned)

    # تبدیل «الی» بین اعداد به «تا» و تبدیل ساعت‌ها یا اعداد ممیزی به فرم گفتاری قبل از حذف علائم
    cleaned = _RE_ELI_BETWEEN_NUMS.sub(r"\1 تا \2", cleaned)
    cleaned = _RE_TIME_OR_DEC.sub(r"\1 و \2", cleaned)

    # حذف یک‌باره تمام علائم نگارشی و نیم‌فاصله‌های باقی‌مانده با جدول ترجمه C
    cleaned = cleaned.translate(_PUNCT_TRANSLATION_TABLE)

    # نرمال‌سازی پاراگراف‌ها
    raw_paragraphs = _RE_PARAGRAPH_SPLIT.split(cleaned)
    clean_paragraphs = []
    for para in raw_paragraphs:
        lines = [
            _RE_SPACES.sub(" ", line).strip()
            for line in para.splitlines()
        ]
        lines = [ln for ln in lines if ln]
        if lines:
            clean_paragraphs.append("\n".join(lines))

    return "\n\n".join(clean_paragraphs)
